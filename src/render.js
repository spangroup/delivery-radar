// Deterministic Markdown rendering of the agent's structured report.

const STATUS = {
  green: '🟢 GREEN',
  amber: '🟠 AMBER',
  red: '🔴 RED',
};
const SEVERITY_ORDER = { high: 0, medium: 1, low: 2 };

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
const withRepo = (e, multiRepo) => (multiRepo && e.repo ? `**${e.repo.split('/')[1]}**: ` : '');

function evidencedList(items, multiRepo) {
  if (!items?.length) return '_None in this period._';
  return items.map((e) => `- ${withRepo(e, multiRepo)}${e.item} _(${e.evidence})_`).join('\n');
}

function plainList(items, empty = '_None._') {
  if (!items?.length) return empty;
  return items.map((s) => `- ${s}`).join('\n');
}

export function renderMarkdown(report, { repos, sinceISO, now, raidItems, meta = {} }) {
  const multiRepo = repos.length > 1;
  const open = raidItems.filter((i) => i.status !== 'closed')
    .sort((a, b) => (SEVERITY_ORDER[a.severity] ?? 3) - (SEVERITY_ORDER[b.severity] ?? 3));
  const closedNow = raidItems.filter((i) => i.status === 'closed' && i.closed_on === now.toISOString().slice(0, 10));

  const raidTable = open.length
    ? [
        '| ID | Type | Severity | Item | Evidence | Mitigation | Since |',
        '|---|---|---|---|---|---|---|',
        ...open.map((i) => `| ${i.id} | ${cell(i.category)} | ${cell(i.severity)} | ${cell(i.title)} | ${cell(i.evidence)} | ${cell(i.mitigation)} | ${cell(i.first_seen)} |`),
      ].join('\n')
    : '_No open items._';

  const closedList = closedNow.length
    ? '\n\n**Closed this period:** ' + closedNow.map((i) => `${i.id} ${i.title}`).join('; ')
    : '';

  const footer = [
    `Generated by Delivery Radar`,
    meta.model ? `model ${meta.model}` : null,
    meta.steps ? `${meta.steps} agent steps` : null,
    meta.usage ? `${meta.usage.input_tokens + meta.usage.output_tokens} tokens` : null,
  ].filter(Boolean).join(' · ');

  return `# Delivery Status — ${now.toISOString().slice(0, 10)}

**Scope:** ${repos.join(', ')}
**Period:** ${sinceISO.slice(0, 10)} → ${now.toISOString().slice(0, 10)}
**Overall:** ${STATUS[report.overall_status] || report.overall_status}: ${report.status_rationale}

## Summary

${report.summary}

## Completed

${evidencedList(report.completed, multiRepo)}

## In progress

${evidencedList(report.in_progress, multiRepo)}

## Next

${plainList(report.next)}

## RAID log

${raidTable}${closedList}

## Decisions needed

${plainList(report.decisions_needed)}

## Estimation & flow

${report.estimation_notes}

## Learnings

${plainList(report.learnings)}

---
_${footer}. Draft for human review: check before sharing._
`;
}
